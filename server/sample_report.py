"""Build the extension's sample report (extension/report/) from the built-in sample run, in design A.

The extension shows a sample run when the local checker is not running; its "Open the full report" opens
extension/report/report.html. That page is the server's own design A page (server.report_a.render_report) for
the invented events in extension/sample_events.js, made fit for an MV3 extension page:
  - every inline <script> moves to its own file next to the page (extension pages forbid inline scripts);
    <script type=application/json> data blocks stay inline (data, never executed)
  - report.js (hand-written, not generated) puts the listing's address (?address=) in place of SAMPLE_ADDRESS
  - a one-line note says this is the built-in sample

Regenerate after changing sample_events.js, server/report_a.py or server/claim_field.py:
    .venv/Scripts/python.exe -m server.sample_report
tests/extension/test_sample_report.py fails while the committed files are out of date.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from server.report_a import render_report

REPO = Path(__file__).resolve().parents[1]
EXT = REPO / "extension"
OUT = EXT / "report"
SAMPLE_JS = EXT / "sample_events.js"
SAMPLE_ADDRESS = "Sample address"  # report.js swaps in the real address from ?address=
NOTE = "Sample result: the local checker was not running, so this is the built-in example."
HEADER = "<!-- Generated by server/sample_report.py from extension/sample_events.js. Do not edit by hand. -->"

_BLOCK = re.compile(r"/\* RC_SAMPLE_EVENTS \*/(.*?)/\* /RC_SAMPLE_EVENTS \*/", re.S)
_SCRIPT = re.compile(r"<script(\s[^>]*)?>(.*?)</script>", re.S | re.I)


def load_events(address: str = SAMPLE_ADDRESS) -> list[dict]:
    """The sample run's events, read from the JSON block in extension/sample_events.js."""
    m = _BLOCK.search(SAMPLE_JS.read_text(encoding="utf-8"))
    if not m:
        raise ValueError("sample_events.js: RC_SAMPLE_EVENTS block not found")

    def fill(o):
        if isinstance(o, dict):
            return {k: fill(v) for k, v in o.items()}
        if isinstance(o, list):
            return [fill(v) for v in o]
        return address if o == "{{address}}" else o

    return fill(json.loads(m.group(1)))


def sample_run() -> dict:
    """A saved run (the shape server.app.load_run returns) for the sample events. No times: the page must not
    depend on when or where it was built."""
    events = load_events()
    run_id = next((e.get("run_id") for e in events if e.get("type") == "run_started"), None) or "sample"
    return {"run_id": run_id, "finished": True, "events": events, "images": {},
            "snapshot": {"address_text": SAMPLE_ADDRESS, "url": "", "title": "the sample listing"}}


def _script_name(code: str) -> str:
    return "claim_field.js" if "cf-data" in code or "cf-panel" in code else "page.js"


def build() -> dict[str, str]:
    """{file name in extension/report/: content}. Pure: nothing is written."""
    html = render_report(sample_run(), live_3d=False)  # no server: still pictures only, never a 3D frame
    files: dict[str, str] = {}

    def externalise(m: re.Match) -> str:
        attrs, code = m.group(1) or "", m.group(2)
        if "src=" in attrs.lower():
            return m.group(0)
        if re.search(r"type\s*=\s*['\"]?application/json", attrs, re.I):
            return m.group(0)  # data block, not executed
        name = _script_name(code)
        if name in files:
            raise ValueError(f"two inline scripts would both go to {name}")
        files[name] = "// " + HEADER[5:-4].strip() + "\n" + code.strip() + "\n"
        return f"<script src='{name}'></script>"

    html = _SCRIPT.sub(externalise, html)

    # the sample note sits under the hero's summary line
    html, n = re.subn(r"(<div class='addr rv'[^>]*><p class=where>.*?</p>(?:<p class=top-line>.*?</p>)?(?:<div class=sum>)?<p>.*?</p>)",
                      lambda m: m.group(1) + f"<p class='meta sample-note'>{NOTE}</p>", html, count=1, flags=re.S)
    if n != 1:
        raise ValueError("hero summary not found: update the sample note anchor in server/sample_report.py")
    html = html.replace("<meta charset=utf-8>", "<meta charset=utf-8>" + HEADER
                        + "<link rel=icon href='../icons/icon32.png'>", 1)
    html = html.replace("</body>", "<script src='report.js'></script></body>", 1)
    files["report.html"] = html
    return files


def main() -> None:
    for name, text in build().items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote extension/report/{name}")


if __name__ == "__main__":
    main()
